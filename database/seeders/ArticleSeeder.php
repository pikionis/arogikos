    /**
     * Build a styled article body using the classes the design's
     * .article-body stylesheet targets (p, h2, h3, ul.dotted, blockquote).
     *
     * @param  array<int, string>  $bullets
     */
    private function buildBody(string $intro, string $bridge, array $bullets = [], ?string $quote = null): string
    {
        $html = "<p>{$intro}</p>\n<p>{$bridge}</p>\n";

        if ($bullets !== []) {
            $html .= "<h2>Τι αξίζει να κρατήσετε</h2>\n<ul class=\"dotted\">\n";
            foreach ($bullets as $bullet) {
                $html .= "  <li>{$bullet}</li>\n";
            }
            $html .= "</ul>\n";
        }

        if ($quote !== null) {
            $html .= "<blockquote>{$quote}</blockquote>\n";
        }

        $html .= "<h2>Πώς βοηθάμε στην Αρωγή</h2>\n";
        $html .= "<p>Κάθε παιδί είναι διαφορετικό, γι' αυτό κάθε πρόγραμμα ξεκινά με ακρόαση και αξιολόγηση. Συνεργαζόμαστε στενά με τους γονείς και το σχολείο, ώστε η στήριξη να είναι συνεπής σε όλα τα περιβάλλοντα της ζωής του παιδιού.</p>\n";
        $html .= '<p>Αν αναγνωρίζετε κάτι από τα παραπάνω και θέλετε να συζητήσουμε, είμαστε εδώ — με χρόνο, γνώση και πολλή φροντίδα.</p>';

        return $html;
    }

